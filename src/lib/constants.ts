export function sectorOf(adSetName?: string): { code: string; label: string } | null {
  const m = adSetName?.match(/\bSEC(\d)\b/i);
  if (!m) return null;
  const code = `SEC${m[1]}`;
  return { code, label: SECTOR_LABELS[code] || code };
}

